(ns rubiks.tables-test
  (:require [clojure.test :refer [deftest is testing]]
            [clojure.test.check :as tc]
            [clojure.test.check.generators :as gen]
            [clojure.test.check.properties :as prop]
            [rubiks.cubie :as cubie]
            [rubiks.moves :as moves]
            [rubiks.phases :as phases]
            [rubiks.tables :as tables]))

(deftest sizes-and-depths-test
  (let [ts @tables/default-tables]
    (is (= [2048 1082565 29400 1327104] (mapv :size ts)))
    (testing "radices from the spec"
      (is (= [[2048] [2187 495] [420 70] [96 24 24 24]] (mapv :radices ts))))
    (testing "exact worst-case distances: 7 + 10 + 13 + 15 = 45"
      (is (= [7 10 13 15] (mapv :max-depth ts))))
    (testing "the goal is the solved cube's coordinate, at distance 0"
      (doseq [p ts]
        (is (= (:goal p) (tables/coordinate p cubie/solved)))
        (is (zero? (tables/distance p (:goal p))))))
    (testing "the half-turn coordinate space is reached up to a parity factor"
      (is (= 663552 (count (filter #(>= % 0) (seq (:dist (nth ts 3))))))))
    (testing "every phase-3 and earlier coordinate is reachable"
      (doseq [p (take 3 ts)]
        (is (every? #(>= % 0) (seq (:dist p))))))))

;; Random states reached by a random walk over the given move ids.
(defn- gen-walk [move-ids]
  (gen/fmap (fn [ids] (cubie/apply-move-ids cubie/solved ids))
            (gen/vector (gen/elements move-ids) 0 40)))

(defn- steps-agree?
  "For every move of the phase, the table transition equals the coordinate of
  the state after really applying the move."
  [phase state]
  (let [c (tables/coordinate phase state)]
    (every? (fn [m]
              (= (tables/next-coordinate phase c m)
                 (tables/coordinate phase (cubie/apply-move-ids state [m]))))
            (:moves phase))))

(deftest transitions-match-cubies-test
  (doseq [i (range 4)
          :let [phase (nth @tables/default-tables i)
                ;; each phase starts inside the group generated by its own moves
                ;; (phase 2: G1, phase 3: G2, phase 4: G3; phase 1: anywhere)
                walk-moves (:moves phase)
                result (tc/quick-check 100 (prop/for-all [s (gen-walk (vec walk-moves))]
                                             (steps-agree? phase s)))]]
    (is (:pass? result) (str "phase " (inc i) ": " (pr-str (:shrunk result))))))
