"""Coordinate spaces for Thistlethwaite's four phases.

Each phase works on a small *coordinate* that identifies the cube's coset of
the next subgroup in the chain ``G0 > G1 > G2 > G3 > G4 = {1}``:

========  ========================================  =========  ==============
Phase     Coordinate                                Size       Moves
========  ========================================  =========  ==============
1 (G0>G1) orientation of 11 edges                   2,048      all 18
2 (G1>G2) 7 corner twists x E-slice edge positions  1,082,565  14 (no F, B, F', B')
3 (G2>G3) corner class mod half-turn group x        29,400     10 (U, D, L2 R2 F2 B2)
          M-slice edge positions among 8 U/D slots
4 (G3>1)  corner perm in half-turn group x          1,327,104  6 half turns
          permutation of each edge slice
========  ========================================  =========  ==============

Every coordinate is a *product* of two independent components ``(a, b)``
packed as ``a * nb + b``, because each move acts on the two components
separately.  A :class:`CoordinateSpace` therefore stores one move table per
component and move; tables of the first component are pre-multiplied by ``nb``
so that the successor of a packed state is ``a_table[m][a] + b_table[m][b]``.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations, permutations
from typing import Callable

from .cube import Cube
from .model import E_SLICE, M_SLICE, MOVE_INDEX, MOVES, S_SLICE


@dataclass(frozen=True)
class CoordinateSpace:
    """A phase's coordinate space: encoding, goal and move tables."""

    name: str
    moves: tuple[int, ...]          #: indices into :data:`rubiks.model.MOVES`
    a_tables: tuple[list[int], ...]  #: per move, ``a -> a_next * nb``
    b_tables: tuple[list[int], ...]  #: per move, ``b -> b_next``
    nb: int
    goal: int
    encode: Callable[[Cube], int]
    size: int


def _indices(names: str) -> tuple[int, ...]:
    return tuple(MOVE_INDEX[n] for n in names.split())


PHASE1_MOVES = _indices("U U' U2 D D' D2 L L' L2 R R' R2 F F' F2 B B' B2")
PHASE2_MOVES = _indices("U U' U2 D D' D2 L L' L2 R R' R2 F2 B2")
PHASE3_MOVES = _indices("U U' U2 D D' D2 L2 R2 F2 B2")
PHASE4_MOVES = _indices("U2 D2 L2 R2 F2 B2")


# -- helpers ---------------------------------------------------------------
def _masks(nbits: int, k: int = 4) -> tuple[list[int], dict[int, int]]:
    """All ``nbits``-bit masks with ``k`` bits set, and their index."""
    masks = sorted(sum(1 << i for i in c) for c in combinations(range(nbits), k))
    return masks, {m: i for i, m in enumerate(masks)}


def _mask_of(positions) -> int:
    return sum(1 << p for p in positions)


def _mask_move(mask: int, src, nbits: int) -> int:
    """Occupancy mask after a move: new slot ``j`` holds what was in ``src[j]``."""
    out = 0
    for j in range(nbits):
        if mask >> src[j] & 1:
            out |= 1 << j
    return out


def _mask_tables(nbits: int, moves, nb_after: int = 1):
    masks, index = _masks(nbits)
    tables = []
    for mi in moves:
        src = MOVES[mi].edge_src
        if any(src[j] >= nbits for j in range(nbits)):
            raise AssertionError("move leaves the tracked slots")
        tables.append([index[_mask_move(m, src, nbits)] * nb_after for m in masks])
    return masks, index, tables


def _half_turn_corner_group() -> list[tuple[int, ...]]:
    """The 96 corner permutations generated by the six half turns (sorted)."""
    gens = [MOVES[MOVE_INDEX[f + "2"]].corner_src for f in "UDLRFB"]
    ident = tuple(range(8))
    seen = {ident}
    todo = [ident]
    while todo:
        p = todo.pop()
        for g in gens:
            q = tuple(p[i] for i in g)
            if q not in seen:
                seen.add(q)
                todo.append(q)
    return sorted(seen)


# -- phase 1: edge orientation ----------------------------------------------
def _phase1() -> CoordinateSpace:
    def encode(cube: Cube) -> int:
        eo = cube.eo
        return sum(eo[i] << i for i in range(11))

    tables = []
    for mi in PHASE1_MOVES:
        m = MOVES[mi]
        table = []
        for v in range(2048):
            eo = [v >> i & 1 for i in range(11)]
            eo.append(sum(eo) & 1)
            new = [eo[i] ^ f for i, f in zip(m.edge_src, m.edge_flip)]
            table.append(sum(new[i] << i for i in range(11)))
        tables.append(table)
    return CoordinateSpace("phase1", PHASE1_MOVES, tuple(tables),
                           tuple([0] for _ in tables), 1, 0, encode, 2048)


# -- phase 2: corner orientation x E-slice positions -------------------------
def _phase2() -> CoordinateSpace:
    masks, index, slice_tables = _mask_tables(12, PHASE2_MOVES)
    nb = len(masks)
    assert nb == 495

    def encode(cube: Cube) -> int:
        co = 0
        for i in range(7):
            co = co * 3 + cube.co[i]
        mask = _mask_of(j for j in range(12) if cube.ep[j] >= 8)
        return co * nb + index[mask]

    twist_tables = []
    for mi in PHASE2_MOVES:
        m = MOVES[mi]
        table = []
        for v in range(2187):
            co = []
            for _ in range(7):
                co.append(v % 3)
                v //= 3
            co.reverse()
            co.append((-sum(co)) % 3)
            new = [(co[i] + t) % 3 for i, t in zip(m.corner_src, m.corner_twist)]
            nv = 0
            for i in range(7):
                nv = nv * 3 + new[i]
            table.append(nv * nb)
        twist_tables.append(table)
    goal = index[_mask_of(E_SLICE)]
    return CoordinateSpace("phase2", PHASE2_MOVES, tuple(twist_tables),
                           tuple(slice_tables), nb, goal, encode, 2187 * nb)


# -- phase 3: corner class x M-slice positions --------------------------------
def _phase3() -> CoordinateSpace:
    group = _half_turn_corner_group()
    assert len(group) == 96

    def canon(cp) -> tuple[int, ...]:
        # Class of cp under relabelling the corner pieces by the group.
        return min(tuple(h[c] for c in cp) for h in group)

    # Enumerate the 420 classes reachable by phase-3 moves, from the identity.
    start = canon(range(8))
    classes = {start: 0}
    reps = [start]
    todo = [start]
    while todo:
        cp = todo.pop()
        for mi in PHASE3_MOVES:
            src = MOVES[mi].corner_src
            nxt = canon([cp[i] for i in src])
            if nxt not in classes:
                classes[nxt] = len(reps)
                reps.append(nxt)
                todo.append(nxt)
    assert len(reps) == 420, len(reps)

    masks, index, edge_tables = _mask_tables(8, PHASE3_MOVES)
    nb = len(masks)
    assert nb == 70
    corner_tables = []
    for mi in PHASE3_MOVES:
        src = MOVES[mi].corner_src
        corner_tables.append([classes[canon([cp[i] for i in src])] * nb for cp in reps])

    def encode(cube: Cube) -> int:
        mask = _mask_of(j for j in range(8) if cube.ep[j] in M_SLICE)
        return classes[canon(cube.cp)] * nb + index[mask]

    goal = 0 * nb + index[_mask_of(M_SLICE)]
    return CoordinateSpace("phase3", PHASE3_MOVES, tuple(corner_tables),
                           tuple(edge_tables), nb, goal, encode, 420 * nb)


# -- phase 4: corner permutation x slice permutations --------------------------
def _phase4() -> CoordinateSpace:
    group = _half_turn_corner_group()
    gindex = {p: i for i, p in enumerate(group)}
    perms = list(permutations(range(4)))
    pindex = {p: i for i, p in enumerate(perms)}
    slices = (M_SLICE, S_SLICE, E_SLICE)
    local = [{pos: k for k, pos in enumerate(sl)} for sl in slices]
    nb = 24 ** 3

    def encode(cube: Cube) -> int:
        e = 0
        for sl, loc in zip(slices, local):
            e = e * 24 + pindex[tuple(loc[cube.ep[pos]] for pos in sl)]
        return gindex[tuple(cube.cp)] * nb + e

    corner_tables = []
    edge_tables = []
    for mi in PHASE4_MOVES:
        m = MOVES[mi]
        corner_tables.append([gindex[tuple(p[i] for i in m.corner_src)] * nb for p in group])
        per_slice = []
        for sl, loc in zip(slices, local):
            table = []
            for p in perms:
                new = tuple(p[loc[m.edge_src[pos]]] for pos in sl)
                table.append(pindex[new])
            per_slice.append(table)
        tm, ts, te = per_slice
        edge_tables.append([tm[v // 576] * 576 + ts[v // 24 % 24] * 24 + te[v % 24]
                            for v in range(nb)])
    goal = gindex[tuple(range(8))] * nb
    return CoordinateSpace("phase4", PHASE4_MOVES, tuple(corner_tables),
                           tuple(edge_tables), nb, goal, encode, 96 * nb)


#: Builders of the four coordinate spaces, in phase order.
PHASES = (_phase1, _phase2, _phase3, _phase4)
