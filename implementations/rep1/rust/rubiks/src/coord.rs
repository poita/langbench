//! Coordinates: compact integers describing the part of a cube state that
//! matters to each phase of the algorithm.
//!
//! | phase | coordinate                                        | size      |
//! |-------|---------------------------------------------------|-----------|
//! | 1     | edge orientation (11 free flips)                  | 2,048     |
//! | 2     | corner twist (7 free) × E-slice edge positions    | 2,187×495 |
//! | 3     | corner class mod half-turn group × M-slice edges  | 420×70    |
//! | 4     | corner in half-turn group × three slice perms     | 96×24³    |
//!
//! Edge cubie numbering (see [`crate::cubie`]): the E-slice edges are cubies
//! 8..12 (`FR FL BL BR`), the M-slice edges are the odd cubies among 0..8
//! (`UF UB DF DB`) and the S-slice edges the even ones (`UR UL DR DL`).

use crate::perm;

pub const N_EO: usize = 2048;
pub const N_CO: usize = 2187;
pub const N_ESLICE: usize = 495;
pub const N_CORNER_CLASS: usize = 420;
pub const N_MSLICE: usize = 70;
pub const N_HALF_TURN_CORNERS: usize = 96;
pub const N_SLICE_PERM: usize = 24;

/// Edge cubies of the three slices, in position order within the slice.
pub const SLICE_EDGES: [[u8; 4]; 3] = [[8, 9, 10, 11], [1, 3, 5, 7], [0, 2, 4, 6]];

/// Edge-orientation coordinate: the first 11 flips as a binary number.
pub fn eo_coord(eo: &[u8; 12]) -> usize {
    (0..11).fold(0, |acc, i| acc | (eo[i] as usize) << i)
}

/// Inverse of [`eo_coord`]; the 12th flip makes the total even.
pub fn eo_decode(c: usize) -> [u8; 12] {
    let mut eo = [0u8; 12];
    for (i, slot) in eo.iter_mut().enumerate().take(11) {
        *slot = ((c >> i) & 1) as u8;
    }
    eo[11] = (c.count_ones() % 2) as u8;
    eo
}

/// Corner-twist coordinate: the first 7 twists as a base-3 number.
pub fn co_coord(co: &[u8; 8]) -> usize {
    (0..7).rev().fold(0, |acc, i| acc * 3 + co[i] as usize)
}

/// Inverse of [`co_coord`]; the 8th twist makes the total a multiple of 3.
pub fn co_decode(mut c: usize) -> [u8; 8] {
    let mut co = [0u8; 8];
    let mut sum = 0;
    for slot in co.iter_mut().take(7) {
        *slot = (c % 3) as u8;
        sum += *slot as usize;
        c /= 3;
    }
    co[7] = ((3 - sum % 3) % 3) as u8;
    co
}

/// Bit mask over edge positions `0..12` marking those holding E-slice cubies.
pub fn eslice_mask(ep: &[u8; 12]) -> u32 {
    (0..12).filter(|&i| ep[i] >= 8).fold(0, |m, i| m | 1 << i)
}

/// Bit mask over the eight non-E positions `0..8` marking those holding an
/// M-slice cubie (an odd cubie). Meaningful when the E-slice edges are home.
pub fn mslice_mask(ep: &[u8; 12]) -> u32 {
    (0..8).filter(|&i| ep[i] & 1 == 1).fold(0, |m, i| m | 1 << i)
}

/// The group generated by the six half turns, acting on corner permutations
/// (96 elements), and the cosets it induces on all 8! corner permutations.
///
/// Corner permutations `p` and `h∘p` (`h` in the group; `(h∘p)[i] = h[p[i]]`)
/// form one class. Applying a move on the right (`p[m[i]]`) maps classes to
/// classes, so a class is a well-defined coordinate.
#[derive(Clone, Debug)]
pub struct CornerGroup {
    /// Elements of the half-turn corner group, sorted by permutation rank.
    pub elements: Vec<[u8; 8]>,
    /// Maps a permutation rank to its index in `elements` (`u8::MAX` if absent).
    pub element_index: Vec<u8>,
    /// Maps a permutation rank to its class id in `0..420`.
    pub class_of: Vec<u16>,
    /// A representative permutation rank for every class.
    pub class_rep: Vec<u16>,
}

impl CornerGroup {
    /// Builds the group and its cosets from the corner action of the half
    /// turns, given as permutations `gens`.
    pub fn new(gens: &[[u8; 8]]) -> CornerGroup {
        const IDENTITY: [u8; 8] = [0, 1, 2, 3, 4, 5, 6, 7];
        let mut elements = vec![IDENTITY];
        let mut seen = vec![false; 40320];
        seen[0] = true;
        let mut head = 0;
        while head < elements.len() {
            let p = elements[head];
            head += 1;
            for g in gens {
                let q: [u8; 8] = std::array::from_fn(|i| p[g[i] as usize]);
                let r = perm::rank(&q);
                if !seen[r] {
                    seen[r] = true;
                    elements.push(q);
                }
            }
        }
        elements.sort_by_key(|p| perm::rank(p));

        let mut element_index = vec![u8::MAX; 40320];
        for (i, p) in elements.iter().enumerate() {
            element_index[perm::rank(p)] = i as u8;
        }

        let mut class_of = vec![u16::MAX; 40320];
        let mut class_rep = Vec::new();
        let mut canon_class = vec![u16::MAX; 40320];
        for r in 0..40320 {
            let p = perm::unrank(8, r);
            let canon = elements
                .iter()
                .map(|h| {
                    let q: [u8; 8] = std::array::from_fn(|i| h[p[i] as usize]);
                    perm::rank(&q)
                })
                .min()
                .unwrap();
            if canon_class[canon] == u16::MAX {
                canon_class[canon] = class_rep.len() as u16;
                class_rep.push(r as u16);
            }
            class_of[r] = canon_class[canon];
        }
        CornerGroup { elements, element_index, class_of, class_rep }
    }

    /// Class id of a corner permutation.
    pub fn class(&self, cp: &[u8; 8]) -> usize {
        self.class_of[perm::rank(cp)] as usize
    }

    /// Index within `elements` of a corner permutation, if it is in the group.
    pub fn element(&self, cp: &[u8; 8]) -> Option<usize> {
        match self.element_index[perm::rank(cp)] {
            u8::MAX => None,
            i => Some(i as usize),
        }
    }
}

/// Rank (0..24) of the arrangement of a slice's four edges: the local index
/// of the cubie at each of the slice's four positions. Returns `None` if a
/// position holds a cubie from another slice.
pub fn slice_perm_coord(ep: &[u8; 12], slice: usize) -> Option<usize> {
    let cubies = &SLICE_EDGES[slice];
    let mut local = [0u8; 4];
    for (l, &pos) in cubies.iter().enumerate() {
        local[l] = cubies.iter().position(|&c| c == ep[pos as usize])? as u8;
    }
    Some(perm::rank(&local))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn eo_round_trip() {
        for c in 0..N_EO {
            assert_eq!(eo_coord(&eo_decode(c)), c);
        }
    }

    #[test]
    fn co_round_trip() {
        for c in 0..N_CO {
            let co = co_decode(c);
            assert_eq!(co_coord(&co), c);
            assert_eq!(co.iter().map(|&x| x as usize).sum::<usize>() % 3, 0);
        }
    }
}
