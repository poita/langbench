package numfmt

import "testing"

func TestFormat(t *testing.T) {
	tests := []struct {
		v    float64
		want string
	}{
		{0, "0"}, {-0.0, "0"}, {42, "42"}, {-7, "-7"}, {123456789012345, "123456789012345"},
		{1e14, "100000000000000"}, {1e15, "1e+15"}, {1e20, "1e+20"}, {-1.5e15, "-1.5e+15"},
		{1.23456789e15, "1.23456789e+15"}, {0.00001, "1e-05"}, {2.5e-10, "2.5e-10"},
		{0.5, "0.5"}, {1234567.891, "1234567.891"}, {1.0 / 3, "0.3333333333"},
		{2.0 / 3, "0.6666666667"}, {0.0001234, "0.0001234"}, {-2.5, "-2.5"},
		{1234567890.4, "1234567890"}, {9999999999.7, "1e+10"}, {1234567890.5, "1234567890"},
		{2500000000.75, "2500000001"}, {1200000000.4, "1200000000"}, {0.1, "0.1"},
		{1e300, "1e+300"}, {1.5e-300, "1.5e-300"}, {0.00012345678901, "0.000123456789"},
		{123456789.25, "123456789.2"}, {123456789.75, "123456789.8"},
	}
	for _, tt := range tests {
		if got := Format(tt.v); got != tt.want {
			t.Errorf("Format(%v) = %q, want %q", tt.v, got, tt.want)
		}
	}
}

func TestAppendKeepsPrefix(t *testing.T) {
	if got := string(Append([]byte("x="), 2.5)); got != "x=2.5" {
		t.Errorf("got %q", got)
	}
}
