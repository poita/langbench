package solver

import (
	"math/bits"

	"example.com/rubiks/cube"
)

// Sizes of the coordinate spaces.
const (
	nEO     = 1 << 11 // phase 1: edge orientations
	nCO     = 2187    // 3^7 corner orientations
	nSlice  = 495     // C(12,4) positions of the E-slice edges
	nCoset  = 420     // 8! / 96 corner permutation classes
	nMComb  = 70      // C(8,4) positions of the M-slice edges
	nHGroup = 96      // corner permutations generated by half turns
	nPerm4  = 24      // 4!
	nPerm8  = 40320   // 8!
)

// combIndex maps a bit mask with exactly k bits set to its rank among all
// such masks of the same width, ordered numerically.
type combIndex struct {
	rank  []int16
	masks []uint16
}

func newCombIndex(width, k int) *combIndex {
	ci := &combIndex{rank: make([]int16, 1<<width)}
	for m := 0; m < 1<<width; m++ {
		ci.rank[m] = -1
		if bits.OnesCount(uint(m)) == k {
			ci.rank[m] = int16(len(ci.masks))
			ci.masks = append(ci.masks, uint16(m))
		}
	}
	return ci
}

var (
	slice12 = newCombIndex(12, 4) // E-slice pieces among the 12 edge slots
	comb8   = newCombIndex(8, 4)  // M-slice pieces among the 8 U/D-layer slots
)

// Edge slices: the four slots (and the four pieces that belong there).
var (
	eSliceSlots = [4]uint8{cube.FR, cube.FL, cube.BL, cube.BR}
	mSliceSlots = [4]uint8{cube.UF, cube.UB, cube.DF, cube.DB}
	sSliceSlots = [4]uint8{cube.UR, cube.UL, cube.DR, cube.DL}
)

// ---- phase 1: edge orientation ------------------------------------------

func eoCoord(c *cube.Cube) int {
	x := 0
	for i := 0; i < 11; i++ {
		x |= int(c.EO[i]) << i
	}
	return x
}

func eoCube(x int) cube.Cube {
	c := cube.Solved()
	p := 0
	for i := 0; i < 11; i++ {
		c.EO[i] = uint8(x >> i & 1)
		p ^= int(c.EO[i])
	}
	c.EO[11] = uint8(p)
	return c
}

// ---- phase 2: corner orientation x E-slice positions --------------------

func coCoord(c *cube.Cube) int {
	x := 0
	for i := 0; i < 7; i++ {
		x = x*3 + int(c.CO[i])
	}
	return x
}

func coCube(x int) cube.Cube {
	c := cube.Solved()
	sum := 0
	for i := 6; i >= 0; i-- {
		c.CO[i] = uint8(x % 3)
		sum += x % 3
		x /= 3
	}
	c.CO[7] = uint8((3 - sum%3) % 3)
	return c
}

func sliceCoord(c *cube.Cube) int {
	m := 0
	for i, p := range c.EP {
		if p >= cube.FR {
			m |= 1 << i
		}
	}
	return int(slice12.rank[m])
}

// sliceCube returns a cube whose E-slice edges occupy the slots of rank x.
func sliceCube(x int) cube.Cube {
	c := cube.Solved()
	m := slice12.masks[x]
	e, o := uint8(cube.FR), uint8(0)
	for i := 0; i < 12; i++ {
		if m>>i&1 == 1 {
			c.EP[i] = e
			e++
		} else {
			c.EP[i] = o
			o++
		}
	}
	return c
}

// ---- phase 3: corner coset x M-slice positions ---------------------------

// mCoord ranks the slots (among 0..7) holding M-slice edges. It requires
// the E-slice edges to be in the E slice.
func mCoord(c *cube.Cube) int {
	m := 0
	for i := 0; i < 8; i++ {
		if p := c.EP[i]; p < 8 && p&1 == 1 { // UF UB DF DB = 1 3 5 7
			m |= 1 << i
		}
	}
	return int(comb8.rank[m])
}

func mCube(x int) cube.Cube {
	c := cube.Solved()
	m := comb8.masks[x]
	mp := [4]uint8{cube.UF, cube.UB, cube.DF, cube.DB}
	sp := [4]uint8{cube.UR, cube.UL, cube.DR, cube.DL}
	a, b := 0, 0
	for i := 0; i < 8; i++ {
		if m>>i&1 == 1 {
			c.EP[i] = mp[a]
			a++
		} else {
			c.EP[i] = sp[b]
			b++
		}
	}
	return c
}

// permRank returns the lexicographic rank of a permutation.
func permRank(p []uint8) int {
	r := 0
	n := len(p)
	for i := 0; i < n; i++ {
		smaller := 0
		for j := i + 1; j < n; j++ {
			if p[j] < p[i] {
				smaller++
			}
		}
		r = r*(n-i) + smaller
	}
	return r
}

// permUnrank is the inverse of permRank for permutations of 0..n-1.
func permUnrank(r, n int, p []uint8) {
	digits := make([]int, n)
	for i := n - 1; i >= 0; i-- {
		digits[i] = r % (n - i)
		r /= n - i
	}
	avail := make([]uint8, n)
	for i := range avail {
		avail[i] = uint8(i)
	}
	for i := 0; i < n; i++ {
		d := digits[i]
		p[i] = avail[d]
		avail = append(avail[:d], avail[d+1:]...)
	}
}

// cornerGroup describes the group H of corner permutations generated by the
// six half turns and the classes Hσ of corner permutations modulo H.
type cornerGroup struct {
	elems   [nHGroup][8]uint8 // the 96 elements of H
	hIndex  []int16           // permRank -> index in elems, or -1
	coset   []uint16          // permRank -> coset id
	cosetRp [nCoset][8]uint8  // a representative of each coset
}

func newCornerGroup() *cornerGroup {
	g := &cornerGroup{hIndex: make([]int16, nPerm8), coset: make([]uint16, nPerm8)}
	for i := range g.hIndex {
		g.hIndex[i] = -1
	}
	var gens [][8]uint8
	for f := cube.U; f <= cube.B; f++ {
		gens = append(gens, cube.MoveCube(cube.NewMove(f, 2)).CP)
	}
	id := cube.Solved().CP
	g.elems[0] = id
	g.hIndex[permRank(id[:])] = 0
	n := 1
	for i := 0; i < n; i++ {
		for _, gen := range gens {
			var q [8]uint8
			for k := range q {
				q[k] = g.elems[i][gen[k]]
			}
			if r := permRank(q[:]); g.hIndex[r] < 0 {
				g.hIndex[r] = int16(n)
				g.elems[n] = q
				n++
			}
		}
	}
	if n != nHGroup {
		panic("solver: half-turn corner group has wrong order")
	}

	for i := range g.coset {
		g.coset[i] = 0xFFFF
	}
	next := 0
	var sigma [8]uint8
	for r := 0; r < nPerm8; r++ {
		if g.coset[r] != 0xFFFF {
			continue
		}
		permUnrank(r, 8, sigma[:])
		g.cosetRp[next] = sigma
		for _, h := range g.elems {
			var q [8]uint8
			for k := range q {
				q[k] = h[sigma[k]]
			}
			g.coset[permRank(q[:])] = uint16(next)
		}
		next++
	}
	if next != nCoset {
		panic("solver: wrong number of corner cosets")
	}
	return g
}

// ---- phase 4 --------------------------------------------------------------

// slicePerm returns the rank of the arrangement of the slice's pieces within
// its four slots, which must hold exactly the pieces of that slice.
func slicePerm(c *cube.Cube, slots *[4]uint8) int {
	var a [4]uint8
	for k, s := range slots {
		p := c.EP[s]
		for j, t := range slots {
			if t == p {
				a[k] = uint8(j)
			}
		}
	}
	return permRank(a[:])
}
