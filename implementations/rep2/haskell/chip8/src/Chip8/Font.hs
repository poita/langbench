-- |
-- Module      : Chip8.Font
-- Description : The built-in hexadecimal font.
--
-- The font is five bytes per glyph for the digits @0@ to @F@, stored in
-- memory starting at 'fontBase'.
module Chip8.Font
  ( fontBase
  , glyphSize
  , fontBytes
  , glyphAddress
  ) where

import Data.Word (Word8)

-- | Address of the first font byte in machine memory (@0x050@).
fontBase :: Int
fontBase = 0x050

-- | Number of bytes per glyph.
glyphSize :: Int
glyphSize = 5

-- | Address of the glyph for the low nibble of the given value.
--
-- >>> glyphAddress 0x1A == 0x050 + 0xA * 5
-- True
glyphAddress :: Int -> Int
glyphAddress v = fontBase + (v `mod` 16) * glyphSize

-- | The 80 font bytes, glyphs @0@..@F@ in order.
fontBytes :: [Word8]
fontBytes =
  [ 0xF0, 0x90, 0x90, 0x90, 0xF0
  , 0x20, 0x60, 0x20, 0x20, 0x70
  , 0xF0, 0x10, 0xF0, 0x80, 0xF0
  , 0xF0, 0x10, 0xF0, 0x10, 0xF0
  , 0x90, 0x90, 0xF0, 0x10, 0x10
  , 0xF0, 0x80, 0xF0, 0x10, 0xF0
  , 0xF0, 0x80, 0xF0, 0x90, 0xF0
  , 0xF0, 0x10, 0x20, 0x40, 0x40
  , 0xF0, 0x90, 0xF0, 0x90, 0xF0
  , 0xF0, 0x90, 0xF0, 0x10, 0xF0
  , 0xF0, 0x90, 0xF0, 0x90, 0x90
  , 0xE0, 0x90, 0xE0, 0x90, 0xE0
  , 0xF0, 0x80, 0x80, 0x80, 0xF0
  , 0xE0, 0x90, 0x90, 0x90, 0xE0
  , 0xF0, 0x80, 0xF0, 0x80, 0xF0
  , 0xF0, 0x80, 0xF0, 0x80, 0x80
  ]
