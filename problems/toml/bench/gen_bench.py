#!/usr/bin/env python3
"""Generates the performance benchmark inputs for the `toml` problem.

Writes bench/NNN_name.in and bench/NNN_name.out in the same layout as tests/,
so `run_tests.py toml --tests-dir problems/toml/bench` runs them.  Every input
is built from a fixed seed, kept under the 8 MB document limit of SPEC.md,
and its expected output comes from reference/main.py.  Each decode result is
cross-checked against Python's tomllib, and the encode result is checked to
round-trip, exactly as gen_tests.py does for the regular tests.
"""
import json
import os
import random
import subprocess
import sys

try:
    import tomllib
except ImportError:
    sys.exit('gen_bench.py needs Python 3.11+ for the tomllib oracle')

HERE = os.path.dirname(os.path.abspath(__file__))
PROBLEM = os.path.dirname(HERE)
REF = os.path.join(PROBLEM, 'reference', 'main.py')

sys.dont_write_bytecode = True
sys.path.insert(0, PROBLEM)
from gen_tests import tagged_from_tomllib, canonical_json  # noqa: E402

# Hard cap from SPEC.md (8 MB documents), with a little slack.
LIMIT = 7_900_000
# Per-input document sizes, chosen so that bench/ with its expected outputs
# stays near 30 MB (decoded tagged JSON is about twice the TOML size).
LOCK_SIZE = 4_000_000
CONFIG_SIZE = 3_400_000
ENCODE_SIZE = 6_500_000

WORDS = ['alpha', 'bravo', 'charlie', 'delta', 'echo', 'foxtrot', 'golf',
         'hotel', 'india', 'juliett', 'kilo', 'lima', 'mike', 'november',
         'oscar', 'papa', 'quebec', 'romeo', 'sierra', 'tango', 'uniform',
         'victor', 'whiskey', 'xray', 'yankee', 'zulu', 'serde', 'tokio',
         'futures', 'proc', 'macro', 'derive', 'core', 'util', 'sys', 'rt']
UNICODE = ['caf\u00e9', '\u4e2d\u6587', '\u2603', '\u00fcber', '\u03bb',
           '\u65e5\u672c', '\U0001F680', '\u00f1and\u00fa']


def crate_name(rng):
    parts = [rng.choice(WORDS) for _ in range(rng.randrange(1, 4))]
    return rng.choice(['-', '_']).join(parts)


def version(rng):
    v = '%d.%d.%d' % (rng.randrange(3), rng.randrange(60), rng.randrange(40))
    if rng.randrange(15) == 0:
        v += '-%s.%d' % (rng.choice(['alpha', 'beta', 'rc']), rng.randrange(5))
    return v


# ---------------------------------------------------------------------------
# 001: a very large Cargo.lock
# ---------------------------------------------------------------------------

def build_lockfile(rng, limit):
    """A Cargo.lock in the exact shape cargo writes, grown to the size limit."""
    out = ['# This file is automatically @generated by Cargo.',
           '# It is not intended for manual editing.', 'version = 4', '']
    names = []
    size = sum(len(x) + 1 for x in out)
    n = 0
    while True:
        name = '%s-%d' % (crate_name(rng), n)
        n += 1
        lines = ['[[package]]', 'name = "%s"' % name,
                 'version = "%s"' % version(rng)]
        if rng.randrange(10):
            lines.append('source = "registry+https://github.com/rust-lang/'
                         'crates.io-index"')
            lines.append('checksum = "%064x"' % rng.getrandbits(256))
        elif rng.randrange(2):
            lines.append('source = "git+https://github.com/%s/%s?rev=%07x#%040x"'
                         % (rng.choice(WORDS), name, rng.getrandbits(28),
                            rng.getrandbits(160)))
        deps = []
        if names:
            for _ in range(min(len(names), rng.choice([0, 1, 2, 3, 5, 8, 13]))):
                dep = rng.choice(names)
                if rng.randrange(6) == 0:
                    dep += ' %s' % version(rng)
                deps.append(dep)
        if deps:
            lines.append('dependencies = [')
            lines.extend(' "%s",' % d for d in deps)
            lines.append(']')
        lines.append('')
        chunk = sum(len(x) + 1 for x in lines)
        if size + chunk + 200 > limit:
            break
        out.extend(lines)
        size += chunk
        names.append(name)
    # The trailing metadata table cargo used to write.
    out.append('[metadata]')
    out.append('"checksum %s" = "%064x"' % (names[0], rng.getrandbits(256)))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------------------
# 002: a dense configuration document using the whole grammar
# ---------------------------------------------------------------------------

def rand_float(rng):
    kind = rng.randrange(10)
    if kind == 0:
        return '%de%s%d' % (rng.randrange(1, 10), rng.choice(['', '+', '-']),
                            rng.randrange(1, 300))
    if kind == 1:
        return '%d.%06de-%02d' % (rng.randrange(10), rng.randrange(10 ** 6),
                                  rng.randrange(1, 40))
    if kind == 2:
        return rng.choice(['inf', '-inf', '+inf', 'nan', '-0.0', '0.0'])
    if kind == 3:
        return '%d_%03d.%d_%d' % (rng.randrange(1, 999), rng.randrange(1000),
                                  rng.randrange(10), rng.randrange(1000))
    return repr(rng.uniform(-1e4, 1e4))


def rand_int(rng):
    kind = rng.randrange(8)
    if kind == 0:
        return '0x%X' % rng.getrandbits(rng.randrange(4, 62))
    if kind == 1:
        return '0o%o' % rng.getrandbits(rng.randrange(3, 62))
    if kind == 2:
        return '0b%s' % bin(rng.getrandbits(rng.randrange(2, 30)) | 1)[2:]
    if kind == 3:
        return '{:,}'.format(rng.getrandbits(48)).replace(',', '_')
    if kind == 4:
        return '-%d' % rng.getrandbits(63)
    return str(rng.randrange(100000))


def rand_date(rng):
    return '%04d-%02d-%02d' % (rng.randrange(1970, 2100), rng.randrange(1, 13),
                               rng.randrange(1, 29))


def rand_time(rng):
    t = '%02d:%02d:%02d' % (rng.randrange(24), rng.randrange(60), rng.randrange(60))
    if rng.randrange(2):
        t += '.' + str(rng.randrange(10 ** rng.randrange(1, 7))).rjust(3, '0')
    return t


def rand_datetime(rng):
    kind = rng.randrange(6)
    sep = rng.choice(['T', 'T', 't', ' '])
    base = rand_date(rng) + sep + rand_time(rng)
    if kind == 0:
        return base
    if kind == 1:
        return rand_date(rng)
    if kind == 2:
        return rand_time(rng)
    if kind == 3:
        return base + rng.choice(['Z', 'z', '+00:00', '-00:00'])
    return base + '%s%02d:%02d' % (rng.choice('+-'), rng.randrange(24),
                                   rng.choice([0, 15, 30, 45]))


def rand_basic(rng):
    pieces = []
    for _ in range(rng.randrange(1, 6)):
        k = rng.randrange(12)
        if k == 0:
            pieces.append(rng.choice(['\\n', '\\t', '\\"', '\\\\', '\\b', '\\f', '\\r']))
        elif k == 1:
            pieces.append('\\u%04X' % rng.choice([0xe9, 0x4e2d, 0x2603, 0x41, 0x7f, 0x1]))
        elif k == 2:
            pieces.append('\\U%08x' % rng.choice([0x1F600, 0x1F680, 0x10FFFF, 0x20AC]))
        elif k == 3:
            pieces.append(rng.choice(UNICODE))
        else:
            pieces.append(rng.choice(WORDS))
    return '"%s"' % ' '.join(pieces)


def rand_string(rng, inline=False):
    k = rng.randrange(10)
    if inline and k in (1, 2):
        k = 3
    if k == 0:
        return "'%s \\d{2} C:\\path\\%s'" % (rng.choice(WORDS), rng.choice(WORDS))
    if k == 1:
        return '"""\n%s line\n  "quoted" %s\\\n     continued %s"""' % (
            rng.choice(WORDS), rng.choice(UNICODE), rng.choice(WORDS))
    if k == 2:
        return "'''\n%s\n raw 'single' %s\n'''" % (rng.choice(WORDS), rng.choice(UNICODE))
    return rand_basic(rng)


def rand_scalar(rng, inline=False):
    k = rng.randrange(6)
    if k == 0:
        return rand_float(rng)
    if k == 1:
        return rand_int(rng)
    if k == 2:
        return rand_datetime(rng)
    if k == 3:
        return rng.choice(['true', 'false'])
    return rand_string(rng, inline)


def rand_key(rng, i=None):
    k = rng.randrange(12)
    word = rng.choice(WORDS)
    if i is not None:
        word = '%s_%d' % (word, i)
    if k == 0:
        return '"%s %s"' % (word, rng.choice(UNICODE))
    if k == 1:
        return "'%s.%s'" % (word, rng.choice(WORDS))
    return word


def rand_value(rng, depth=0, inline=False):
    """A value; `inline` values sit in an inline table and stay on one line."""
    k = rng.randrange(10)
    if depth < 2 and k == 0:
        items = [rand_scalar(rng, inline) for _ in range(rng.randrange(0, 6))]
        return '[%s]' % ', '.join(items)
    if depth < 2 and k == 1:
        n = rng.randrange(1, 5)
        pairs = ['%s = %s' % (rand_key(rng, j), rand_value(rng, depth + 1, True))
                 for j in range(n)]
        return '{ %s }' % ', '.join(pairs)
    if depth < 2 and k == 2 and not inline:
        rows = ['[%s]' % ', '.join(rand_float(rng) for _ in range(4))
                for _ in range(rng.randrange(1, 4))]
        return '[\n  %s,  # matrix\n]' % ',\n  '.join(rows)
    return rand_scalar(rng, inline)


def emit_pairs(rng, out, count, dotted=True):
    """Writes `count` distinct pairs, some through dotted keys."""
    for i in range(count):
        if dotted and rng.randrange(5) == 0:
            key = '%s . %s.%s' % (rng.choice(['opts', 'limits', 'net']),
                                  rand_key(rng, i), rand_key(rng))
        else:
            key = rand_key(rng, i)
        comment = '  # %s' % rng.choice(WORDS) if rng.randrange(6) == 0 else ''
        out.append('%s = %s%s' % (key, rand_value(rng), comment))


def build_config(rng, limit):
    """A deep, heavily cross-referenced configuration using every grammar form."""
    out = ['# Fleet configuration, generated.', 'title = "fleet \u2603"',
           'schema = 0x0001_0002', 'generated = 2024-06-01T12:00:00.250-07:00', '']
    size = 0
    region_i = 0
    while size < limit:
        region = 'region_%d' % region_i
        region_i += 1
        chunk = []
        # A deep header first, then its parent: implicit table made explicit.
        chunk.append('[%s.zones."%s-a".defaults]' % (region, region))
        emit_pairs(rng, chunk, rng.randrange(3, 8))
        chunk.append('')
        chunk.append('[ %s ]  # explicit after implicit' % region)
        emit_pairs(rng, chunk, rng.randrange(5, 15))
        chunk.append('')
        for s in range(rng.randrange(4, 10)):
            svc = '%s-svc-%d' % (rng.choice(WORDS), s)
            chunk.append('[[%s.service]]' % region)
            chunk.append('name = "%s"' % svc)
            chunk.append('started = %s' % rand_datetime(rng))
            emit_pairs(rng, chunk, rng.randrange(4, 12))
            chunk.append('')
            chunk.append('[%s.service.env]' % region)
            for e in range(rng.randrange(2, 8)):
                chunk.append('%s_%d = %s' % (rng.choice(WORDS).upper(), e,
                                             rand_basic(rng)))
            chunk.append('')
            for p in range(rng.randrange(1, 4)):
                chunk.append('[[%s.service.port]]' % region)
                chunk.append('number = %d' % rng.randrange(1, 65536))
                chunk.append('weights = [%s]' % ', '.join(rand_float(rng) for _ in range(6)))
                emit_pairs(rng, chunk, rng.randrange(1, 4), dotted=False)
                chunk.append('')
        # A wide flat table: many keys to sort.
        chunk.append('[%s.inventory]' % region)
        for h in range(rng.randrange(40, 120)):
            chunk.append('"host-%05d.%s" = { ip = "10.%d.%d.%d", up = %s, '
                         'load = %s, seen = %s }'
                         % (h, rng.choice(WORDS),
                            rng.randrange(256), rng.randrange(256), rng.randrange(256),
                            rng.choice(['true', 'false']), rand_float(rng),
                            rand_datetime(rng)))
        chunk.append('')
        text = '\n'.join(chunk) + '\n'
        size += len(text.encode('utf-8'))
        out.append(text)
    return '\n'.join(out)


def fit(build, seed, limit, budget):
    """Shrinks the size target until the built document fits in `budget` bytes."""
    while True:
        doc = build(random.Random(seed), limit)
        if len(doc.encode('utf-8')) <= budget:
            return doc
        limit = int(limit * 0.97)


# ---------------------------------------------------------------------------
# 003: encode of a large tagged tree
# ---------------------------------------------------------------------------

def shuffle_keys(rng, v):
    if isinstance(v, list):
        return [shuffle_keys(rng, x) for x in v]
    if isinstance(v, dict):
        items = list(v.items())
        rng.shuffle(items)
        return {k: shuffle_keys(rng, x) for k, x in items}
    return v


def build_encode_input(rng, size=ENCODE_SIZE):
    """A config + lockfile tree as tagged JSON, members in random order."""
    def make(limit):
        r = random.Random(rng.random())
        doc = build_config(r, limit)
        tagged = json.loads(run_reference('decode', doc.encode('utf-8')))
        tagged = shuffle_keys(r, tagged)
        return json.dumps(tagged, ensure_ascii=False, separators=(',', ':'))
    limit = size // 2
    while True:
        body = make(limit)
        if len(body.encode('utf-8')) <= size:
            return body
        limit = int(limit * 0.95)


# ---------------------------------------------------------------------------

def run_reference(mode, body):
    data = mode.encode('ascii') + b'\n' + body
    proc = subprocess.run([sys.executable, REF], input=data,
                          capture_output=True, timeout=1800)
    if proc.returncode != 0:
        raise AssertionError('reference failed: %s' % proc.stderr.decode()[:400])
    return proc.stdout.decode('utf-8')


def check_decode(name, body, output):
    text = output.rstrip('\n')
    assert text != 'error', '%s: reference rejected the document' % name
    expected = canonical_json(tagged_from_tomllib(tomllib.loads(body.decode('utf-8'))))
    assert expected == text, '%s: tomllib disagrees with the reference' % name


def check_encode(name, body, output):
    original = canonical_json(json.loads(body.decode('utf-8')))
    back = run_reference('decode', output.encode('utf-8')).rstrip('\n')
    assert back == original, '%s: round trip differs' % name
    lib = canonical_json(tagged_from_tomllib(tomllib.loads(output)))
    assert lib == original, '%s: tomllib disagrees with the encoded document' % name


# Long tier (../bench-long): the same three documents scaled up (decode
# inputs 4x, the encode input 3x; SPEC.md allows 20 MB documents in the long
# tier). Both modes are linear in the document and one document is allowed
# per input, so the document size is the only lever.
LONG_DIR = os.path.join(PROBLEM, 'bench-long')
LONG_LIMIT = 20_000_000


def long_cases():
    return [
        ('001_decode_cargo_lock', 'decode',
         build_lockfile(random.Random(11001), 4 * LOCK_SIZE)),
        ('002_decode_dense_config', 'decode',
         fit(build_config, 11002, 4 * CONFIG_SIZE, 4 * CONFIG_SIZE)),
        ('003_encode_config_tree', 'encode',
         build_encode_input(random.Random(11003), 3 * ENCODE_SIZE)),
    ]


def main():
    long = '--long' in sys.argv[1:]
    if long:
        out_dir, limit = LONG_DIR, LONG_LIMIT
        os.makedirs(out_dir, exist_ok=True)
        cases = long_cases()
    else:
        out_dir, limit = HERE, LIMIT
        cases = [
            ('001_decode_cargo_lock', 'decode',
             build_lockfile(random.Random(1001), LOCK_SIZE)),
            ('002_decode_dense_config', 'decode',
             fit(build_config, 1002, CONFIG_SIZE, CONFIG_SIZE)),
            ('003_encode_config_tree', 'encode',
             build_encode_input(random.Random(1003))),
        ]
    for f in os.listdir(out_dir):
        if f.endswith('.in') or f.endswith('.out'):
            os.remove(os.path.join(out_dir, f))
    for base, mode, body in cases:
        body = body.encode('utf-8')
        assert len(body) <= limit, base
        output = run_reference(mode, body)
        if mode == 'decode':
            check_decode(base, body, output)
        else:
            check_encode(base, body, output)
        with open(os.path.join(out_dir, base + '.in'), 'wb') as f:
            f.write(mode.encode('ascii') + b'\n' + body)
        with open(os.path.join(out_dir, base + '.out'), 'w', encoding='utf-8') as f:
            f.write(output)
        print('%s: %d bytes in, %d bytes out' % (base, len(body), len(output.encode('utf-8'))))


if __name__ == '__main__':
    main()
